"""Generate the synthetic MRTS-shaped monthly fixture.

Authored synthetic demonstration data. Fictional category codes. Not derived from
any Census series or any other dataset. Seed 42, 10 years, seasonality + trend +
noise. Writes examples/fixtures/v1/mrts_synthetic.csv and FIXTURE.md.

Usage: python tools/make_fixture.py --seed 42 [--out examples/fixtures/v1]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

N_YEARS = 10
START = "2016-01"
CATEGORIES = {
    # fictional codes; level in abstract units, trend per month, seasonal amplitude, noise sd (relative)
    "SYN-RET-01": dict(level=12000.0, trend=0.0025, amp=0.18, noise=0.03),
    "SYN-RET-02": dict(level=4500.0, trend=0.0010, amp=0.35, noise=0.05),
    "SYN-RET-03": dict(level=800.0, trend=-0.0015, amp=0.10, noise=0.08),
}


def make_series(rng: np.random.Generator, n: int, level: float, trend: float, amp: float, noise: float) -> np.ndarray:
    t = np.arange(n)
    seasonal = 1.0 + amp * np.sin(2 * np.pi * (t + 10) / 12.0) + 0.5 * amp * (t % 12 == 11)
    growth = (1.0 + trend) ** t
    eps = rng.normal(0.0, noise, size=n)
    y = level * growth * seasonal * (1.0 + eps)
    return np.round(np.maximum(y, 0.0), 0)


def build(seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    n = 12 * N_YEARS
    months = pd.period_range(START, periods=n, freq="M").strftime("%Y-%m")
    frames = []
    for code, p in CATEGORIES.items():
        y = make_series(rng, n, **p)
        frames.append(
            pd.DataFrame(
                {
                    "category_code": code,
                    "data_type_code": "SM",
                    "seasonally_adj": "no",
                    "time": months,
                    "cell_value": y.astype(int),
                }
            )
        )
    return pd.concat(frames, ignore_index=True)


FIXTURE_MD = """# Fixture v1

Authored synthetic demonstration data. Fictional identifiers. Not derived from any
person, company, account or dataset. Generated by `tools/make_fixture.py` seed `{seed}`,
version v1 (`mrts_synthetic.csv`) and by `tools/make_sku_fixture.py` seed `{seed}`,
version v1 (`sku_demand.csv`).

## mrts_synthetic.csv

MRTS-shaped monthly table: `category_code, data_type_code, seasonally_adj, time,
cell_value`. Three fictional categories (`SYN-RET-01..03`), {n_years} years from {start},
each built as level x (1 + trend)^t x seasonal factor x (1 + noise). Values are in
abstract units and carry no meaning outside this repository. This file stands in
for a Census MRTS response only in shape; it is not Census data.

## sku_demand.csv

Weekly integer demand for fictional SKU/store pairs (`SYN-SKU-0001..`, `SYN-STORE-01..`),
negative binomial counts with a yearly cycle. Used only by the replenishment
simulator. It is generated independently of `mrts_synthetic.csv` and the two are
never combined.
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "examples" / "fixtures" / "v1")
    args = ap.parse_args(argv)
    df = build(args.seed)
    args.out.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.out / "mrts_synthetic.csv", index=False)
    (args.out / "FIXTURE.md").write_text(FIXTURE_MD.format(seed=args.seed, n_years=N_YEARS, start=START), encoding="utf-8")
    print(f"wrote {args.out / 'mrts_synthetic.csv'} ({len(df)} rows, {df['category_code'].nunique()} categories)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
